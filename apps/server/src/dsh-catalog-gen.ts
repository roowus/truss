/**
 * Generated dsh model catalog (issue #232).
 *
 * ## Why this exists
 *
 * dsh's ACP picker is fed by `session/new` → `configOptions.model`, so it is
 * exactly as wide as the profile dsh was booted with. Truss boots it with
 * `--profile acp --patch config/truss-dsh-acp.yml`, and that patch's
 * `llm-pi-ai` block carried 27 hand-written fireworks entries — which is why
 * the report was 27, not the 113 configured in the *web* profile's
 * `cordis.patch.yml` (a different profile, a different process, never loaded
 * by the acp profile). Dumping the raw configOptions both ways settled it:
 *
 *   --patch config/truss-dsh-acp.yml  -> 27 leaves, all fireworks
 *   (no patch)                        ->  3 leaves, deepseek-official
 *
 * So the fix is not to reconcile two lists at the picker; it is to stop
 * hand-maintaining the list inside the profile and GENERATE it from the same
 * live key-proxy catalog pi already uses (`pi-config.ts`), which is why pi
 * was always correct and rich.
 *
 * ## Where it is written, and why there
 *
 * The generated patch goes to the runtime data dir (`dataDir`, i.e.
 * `apps/server/data/` or `$TRUSS_DATA_DIR`) — deliberately OUTSIDE the repo
 * tree. A boot-time write inside the checkout would dirty `git status` for
 * every worker and for the audit, which is a self-inflicted version of the
 * shared-checkout problem the work-session rules exist to prevent. The
 * hand-written `config/truss-dsh-acp.yml` is never modified either: the
 * Config panel reads it (`router.ts`), and silently changing what that panel
 * reports would be a regression in a different feature.
 *
 * ## Failure behaviour
 *
 * Generation is best-effort and must never make the picker narrower than it
 * already is: on any failure the caller points `--patch` at nothing extra, so
 * dsh keeps reporting the static 27. An all-empty catalog (every route
 * reachable but returning zero models) counts as a failure for the same
 * reason — writing an empty providers map would drop dsh to the stock 3.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { dataDir } from "./db.js";
import { catalogForPickers, modelCatalog, type CatalogProvider } from "./modelcat.js";

/* Test seam: the catalog sources are injectable so the failure paths (route
   errors, key-proxy down, all-empty) can be exercised without a live proxy.
   Production never sets this. */
export interface CatalogSources {
  modelCatalog: typeof modelCatalog;
  catalogForPickers: typeof catalogForPickers;
}
export const __sources: CatalogSources = { modelCatalog, catalogForPickers };

/** the generated patch filename inside the runtime data dir */
const GENERATED_NAME = "truss-dsh-acp-models.yml";

/** absolute path of the generated patch (may not exist yet) */
export function generatedPatchPath(): string {
  return join(dataDir, GENERATED_NAME);
}

interface CatalogRow {
  provider: string;
  model: string;
}

/** providers the key-proxy catalog knows but that produced no rows — a route
    whose credentials exist but whose models never reached a picker. Surfacing
    this is the "make it loud" half of the fix: silently offering nothing is
    how the original 27-row report went unnoticed for so long. */
export function catalogGaps(providers: CatalogProvider[], rows: CatalogRow[]): { provider: string; reason: string }[] {
  const have = new Set(rows.map((r) => r.provider));
  return providers
    .filter((p) => !have.has(p.id))
    .map((p) => ({ provider: p.id, reason: p.error ? `route error: ${p.error}` : "no rows" }));
}

function yamlString(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/**
 * Render the `--patch` document that supplies dsh's `llm-pi-ai` provider
 * groups. Pure, so the shape is testable without a key-proxy.
 *
 * This mirrors the hand-written block in `config/truss-dsh-acp.yml`
 * (`apiKeyEnv`, `api`, `baseURL`, `displayName`, `models`) so the generated
 * layer is a drop-in second `--patch`. dsh applies patches in order, so this
 * one replaces the providers map the static file supplies.
 */
export function renderDshCatalogPatch(providers: CatalogProvider[], rows: CatalogRow[]): string {
  const byProvider = new Map<string, CatalogRow[]>();
  for (const r of rows) {
    const list = byProvider.get(r.provider) ?? [];
    list.push(r);
    byProvider.set(r.provider, list);
  }

  const lines: string[] = [
    "# GENERATED by Truss (issue #232) — do not edit, do not commit.",
    `# Source: the live key-proxy model catalog (${rows.length} models across ${byProvider.size} providers).`,
    "# Passed to dsh as a second --patch so the ACP report matches the credentials",
    "# the box actually has. config/truss-dsh-acp.yml stays hand-written and untouched.",
    "- id: llm-pi-ai",
    "  config:",
    "    providers:",
  ];

  for (const p of providers) {
    const list = byProvider.get(p.id);
    if (!list?.length) continue; // never emit an empty group
    lines.push(`      ${p.id}:`);
    lines.push(`        apiKeyEnv: AGENT_PROXY_KEY`);
    lines.push(`        api: openai-completions`);
    lines.push(`        baseURL: ${yamlString(p.endpoint)}`);
    lines.push(`        displayName: ${yamlString(p.name)}`);
    lines.push(`        models:`);
    for (const r of list) {
      lines.push(`          - id: ${r.model}`);
      lines.push(`            name: ${yamlString(r.model.split("/").pop() ?? r.model)}`);
      lines.push(`            input: [text]`);
    }
  }

  return lines.join("\n") + "\n";
}

export interface DshCatalogSyncResult {
  ok: boolean;
  /** where the patch was written ("" when generation failed) */
  patchPath: string;
  models: number;
  providers: number;
  /** routes with credentials but no rows — reported, never silently dropped */
  gaps: { provider: string; reason: string }[];
  /** false when identical content was already on disk (no phantom churn) */
  wrote: boolean;
}

/**
 * Generate the dsh catalog patch from the live key-proxy catalog. Never
 * throws: any failure reads as `{ ok: false }` and the caller leaves dsh on
 * its static 27 rather than pointing it at a thin or empty catalog.
 */
export async function syncDshCatalogPatch(): Promise<DshCatalogSyncResult> {
  const empty: DshCatalogSyncResult = { ok: false, patchPath: "", models: 0, providers: 0, gaps: [], wrote: false };
  try {
    const [providers, rows] = await Promise.all([__sources.modelCatalog(), __sources.catalogForPickers()]);
    const usable = rows.filter((r) => r.provider && r.model);
    /* zero rows is a FAILURE, not a valid catalog: writing it would drop dsh
       to the stock 3 deepseek-official rows (#229's "never empty the picker") */
    if (!usable.length) return empty;

    const yml = renderDshCatalogPatch(providers, usable);
    const path = generatedPatchPath();
    const gaps = catalogGaps(providers, usable);
    const providerCount = new Set(usable.map((r) => r.provider)).size;

    let wrote = false;
    try {
      if (readFileSync(path, "utf8") !== yml) {
        mkdirSync(dataDir, { recursive: true });
        writeFileSync(path, yml);
        wrote = true;
      }
    } catch {
      /* unreadable (missing) or unwritable: attempt the write, and if that
         fails the caller keeps the static catalog */
      mkdirSync(dataDir, { recursive: true });
      writeFileSync(path, yml);
      wrote = true;
    }

    return { ok: true, patchPath: path, models: usable.length, providers: providerCount, gaps, wrote };
  } catch {
    /* key-proxy down, disk full, malformed response — dsh keeps the 27 */
    return empty;
  }
}
